"""Generate dashboard charts (matplotlib) + an HTML dashboard page."""

import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

plt.style.use("seaborn-v0_8-whitegrid") if "seaborn-v0_8-whitegrid" in plt.style.available else None


def chart_predicted_vs_actual(predictions, out_path):
    """Scatter of predicted vs actual wait times."""
    cats = sorted({c for _, c, _, _ in predictions})
    colors = {"general": "#4e79a7", "followup": "#f28e2b", "urgent": "#e15759"}
    fig, ax = plt.subplots(figsize=(7, 5))
    for c in cats:
        px = [p for _, cc, p, _ in predictions if cc == c]
        ax_ = [a for _, cc, _, a in predictions if cc == c]
        ax.scatter(px, ax_, label=c, color=colors.get(c), alpha=0.7, s=36)
    lim = max([p for _, _, p, _ in predictions] + [a for _, _, _, a in predictions] + [1])
    ax.plot([0, lim], [0, lim], "k--", lw=1, label="perfect prediction")
    ax.set_xlabel("Predicted wait (min)")
    ax.set_ylabel("Actual wait (min)")
    ax.set_title("MediQueue: predicted vs actual wait times")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_path, dpi=120)
    plt.close(fig)
    return out_path


def chart_queue_timeline(events, out_path):
    """Queue length and served count over the clinic day."""
    times, qlen, served = [], [], []
    cur_q, cur_s = 0, 0
    for t, msg in events:
        if "Ticket " in msg and "taken" in msg:
            cur_q += 1
        elif "Doctor starts" in msg:
            cur_q -= 1
        elif "done | predicted" in msg:
            cur_s += 1
        times.append(t); qlen.append(cur_q); served.append(cur_s)
    fig, ax = plt.subplots(figsize=(8, 4.5))
    ax.plot(times, qlen, label="Waiting in queue", color="#e15759", lw=2)
    ax.plot(times, served, label="Cumulative served", color="#59a14f", lw=2)
    ax.set_xlabel("Minutes since midnight")
    ax.set_ylabel("Patients")
    ax.set_title("Clinic day: queue length & throughput")
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_path, dpi=120)
    plt.close(fig)
    return out_path


